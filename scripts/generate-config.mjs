/**
 * Generates two files at build time from environment variables:
 *   1. src/environments/generated-config.ts  — the values that personalize the site
 *   2. src/themes/_active-theme.scss          — selects which theme is compiled
 *
 * Runs before every `npm start` and `npm run build`. Every variable is
 * optional and falls back to a sensible default, so the template builds and
 * runs with zero configuration. See .env.example for the full list.
 */
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');

const env = process.env;

// ── 1. Site configuration ──────────────────────────────────────────────────
const storageProvider = env.STORAGE_PROVIDER === 'google-sheets' ? 'google-sheets' : 'static-json';

let socialLinks = [];
if (env.SOCIAL_LINKS_JSON) {
  try {
    const parsed = JSON.parse(env.SOCIAL_LINKS_JSON);
    if (Array.isArray(parsed)) socialLinks = parsed;
  } catch {
    console.warn('[generate-config] SOCIAL_LINKS_JSON is not valid JSON; ignoring.');
  }
}

const donationsTitle = env.DONATIONS_TITLE || 'Our Classroom Wish List';

// The "how it works" steps shown on the landing page. Teachers can override the
// whole list with HOW_IT_WORKS_JSON (an array of {title, body}) — a good place
// to explain where the commission goes — or pass an empty array to hide the
// section entirely. Falls back to these three default steps.
const defaultHowItWorks = [
  {
    title: 'Browse the list',
    body: `Visit the ${donationsTitle} to see exactly what our classroom needs this year.`,
  },
  {
    title: 'Pick an item',
    body: 'Every item links straight to Amazon. Choose anything in your budget — every bit helps.',
  },
  {
    title: 'Make a difference',
    body: 'Your purchase stocks our room at no extra cost to you. Thank you for supporting our students.',
  },
];

let howItWorks = defaultHowItWorks;
if (env.HOW_IT_WORKS_JSON) {
  try {
    const parsed = JSON.parse(env.HOW_IT_WORKS_JSON);
    if (Array.isArray(parsed)) {
      howItWorks = parsed
        .filter((step) => step && typeof step.title === 'string' && typeof step.body === 'string')
        .map((step) => ({ title: step.title, body: step.body }));
    }
  } catch {
    console.warn('[generate-config] HOW_IT_WORKS_JSON is not valid JSON; using the default steps.');
  }
}

const config = {
  siteTitle: env.SITE_TITLE || 'Our Classroom Portal',
  siteTagline: env.SITE_TAGLINE || 'A little help goes a long way',
  siteDescription:
    env.SITE_DESCRIPTION ||
    'Our classroom supply wish list. Donations through these links help stock our room at no extra cost to you.',
  siteUrl: env.SITE_URL || 'https://example.com',
  donationsTitle,
  donationsIntro:
    env.DONATIONS_INTRO ||
    'These are the supplies our class is hoping for this year. Each link goes straight to the item on Amazon.',
  contactEmail: env.CONTACT_EMAIL || 'teacher@example.com',
  amazonAssociateTag: env.AMAZON_ASSOCIATE_TAG || '',
  storageProvider,
  googleSheetCsvUrl: env.GOOGLE_SHEET_CSV_URL || '',
  themeIndex: clampThemeIndex(env.THEME_INDEX),
  socialLinks,
  howItWorks,
};

const configTs = `// ---------------------------------------------------------------------------
// AUTO-GENERATED by scripts/generate-config.mjs from environment variables.
// Do not edit by hand — your changes will be overwritten on the next build.
// ---------------------------------------------------------------------------
export type StorageProvider = 'google-sheets' | 'static-json';

export interface SocialLink {
  label: string;
  href: string;
}

export interface HowItWorksStep {
  title: string;
  body: string;
}

export const generatedConfig = {
  siteTitle: ${j(config.siteTitle)},
  siteTagline: ${j(config.siteTagline)},
  siteDescription: ${j(config.siteDescription)},
  siteUrl: ${j(config.siteUrl)},
  donationsTitle: ${j(config.donationsTitle)},
  donationsIntro: ${j(config.donationsIntro)},
  contactEmail: ${j(config.contactEmail)},
  amazonAssociateTag: ${j(config.amazonAssociateTag)},
  storageProvider: ${j(config.storageProvider)} as StorageProvider,
  googleSheetCsvUrl: ${j(config.googleSheetCsvUrl)},
  themeIndex: ${config.themeIndex},
  socialLinks: ${JSON.stringify(config.socialLinks)} as SocialLink[],
  howItWorks: ${JSON.stringify(config.howItWorks)} as HowItWorksStep[],
};
`;

writeFileSync(resolve(root, 'src/environments/generated-config.ts'), configTs, 'utf-8');

// ── 2. Active theme selection ───────────────────────────────────────────────
const THEME_FILES = ['theme-custom', 'theme-1', 'theme-2', 'theme-3', 'theme-4'];
const themeFile = THEME_FILES[config.themeIndex] ?? THEME_FILES[0];

const activeThemeScss = `// AUTO-GENERATED by scripts/generate-config.mjs — do not edit by hand.
// Selected via the THEME_INDEX environment variable (0 = your custom theme).
@use '${themeFile}';
`;

writeFileSync(resolve(root, 'src/themes/_active-theme.scss'), activeThemeScss, 'utf-8');

console.log(
  `[generate-config] wrote site config (storage: ${config.storageProvider}) and theme ${config.themeIndex} (${themeFile}).`,
);

// ── helpers ──────────────────────────────────────────────────────────────────
function clampThemeIndex(raw) {
  const n = Number.parseInt(raw ?? '', 10);
  if (Number.isNaN(n) || n < 0 || n > 4) return 0;
  return n;
}

function j(value) {
  return JSON.stringify(value ?? '');
}
